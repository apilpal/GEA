"""
Chart service for data visualization and analytics.

This module provides business logic for generating chart data used in the
school management system's dashboard and reports. It queries the database
to aggregate and format data for various chart types including student
distribution, revenue analysis, and performance metrics.

The service generates chart configurations with standardized structure
including labels, values, colors, and metadata suitable for frontend
charting libraries.

Chart Types Supported:
- Student Distribution: Bar chart showing students per driver
- Revenue by Driver: Pie chart showing revenue contribution per driver
- Revenue by Class: Bar chart showing revenue by student grade level

All methods are static and designed for high performance with proper
error handling and logging.
"""

import logging
from fastapi import HTTPException
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select, func
from ..core.models import DBStudent, DBDriver

logger = logging.getLogger(__name__)

class ChartService:
    """Service class for generating chart data from school management data.

    Provides static methods for creating various chart configurations
    used in dashboard visualizations and reports. All methods query
    the database and format results for frontend chart consumption.
    """

    @staticmethod
    async def get_student_distribution_chart_data(db: AsyncSession) -> dict:
        """Generate chart data showing student distribution across drivers.

        Creates a bar chart configuration showing how many students are
        assigned to each driver. Useful for understanding transport capacity
        and driver workload distribution.

        Args:
            db (AsyncSession): Async database session for querying student and driver data

        Returns:
            dict: Chart configuration with standardized structure:
                  {
                    "labels": [driver names],
                    "values": [student counts],
                    "colors": [color palette],
                    "type": "bar",
                    "title": "Student Distribution by Driver"
                  }

        Raises:
            HTTPException: If database queries fail during chart generation
        """
        try:
            logger.info("Starting student distribution chart generation")
            logger.info(f"Database session type: {type(db)}")
            # Get all drivers with their student counts
            db_drivers_result = await db.execute(select(DBDriver))
            db_drivers = db_drivers_result.scalars().all()
            logger.info(f"Successfully retrieved {len(db_drivers)} drivers using select()")
            labels = []
            values = []
            colors = ['#667eea', '#764ba2', '#f093fb', '#f5576c', '#4facfe', '#00f2fe']

            for i, db_driver in enumerate(db_drivers):
                student_count_result = await db.execute(
                    select(func.count(DBStudent.id)).where(DBStudent.route == db_driver.name)
                )
                student_count = student_count_result.scalar()
                labels.append(db_driver.name)
                values.append(student_count)

            return {
                "labels": labels,
                "values": values,
                "colors": colors[:len(labels)],
                "type": "bar",
                "title": "Student Distribution by Driver"
            }
        except Exception as e:
            raise HTTPException(status_code=500, detail=f"Error generating student distribution chart: {str(e)}")

    @staticmethod
    async def get_revenue_by_driver_chart_data(db: AsyncSession) -> dict:
        """Generate chart data showing revenue breakdown by individual drivers.

        Creates a pie chart configuration showing the proportion of total
        transport revenue generated by each driver's students. Only includes
        drivers with positive revenue.

        Args:
            db (AsyncSession): Async database session for querying revenue data

        Returns:
            dict: Chart configuration for pie chart with structure:
                  {
                    "labels": [driver names with revenue],
                    "values": [total revenue amounts],
                    "colors": [color palette],
                    "type": "pie",
                    "title": "Revenue by Driver"
                  }

        Raises:
            HTTPException: If database queries fail during chart generation
        """
        try:
            # Get revenue by driver
            db_drivers_result = await db.execute(select(DBDriver))
            db_drivers = db_drivers_result.scalars().all()
            labels = []
            values = []
            colors = ['#667eea', '#764ba2', '#f093fb', '#f5576c', '#4facfe', '#00f2fe']

            for i, db_driver in enumerate(db_drivers):
                driver_revenue_result = await db.execute(
                    select(DBStudent.fees).where(DBStudent.route == db_driver.name)
                )
                driver_revenue = driver_revenue_result.scalars().all()
                revenue = sum(fee for fee in driver_revenue if fee is not None)
                if revenue > 0:  # Only include drivers with revenue
                    labels.append(db_driver.name)
                    values.append(revenue)

            return {
                "labels": labels,
                "values": values,
                "colors": colors[:len(labels)],
                "type": "pie",
                "title": "Revenue by Driver"
            }
        except Exception as e:
            raise HTTPException(status_code=500, detail=f"Error generating revenue by driver chart: {str(e)}")

    @staticmethod
    async def get_revenue_by_class_chart_data(db: AsyncSession) -> dict:
        """Generate chart data showing revenue breakdown by student classes.

        Creates a bar chart configuration showing total transport revenue
        generated by students in each class/grade level. Results are sorted
        by revenue amount in descending order.

        Args:
            db (AsyncSession): Async database session for querying student fee data

        Returns:
            dict: Chart configuration for bar chart with structure:
                  {
                    "labels": [class names, sorted by revenue],
                    "values": [total revenue per class],
                    "colors": [extended color palette],
                    "type": "bar",
                    "title": "Revenue by Class"
                  }

        Raises:
            HTTPException: If database queries fail during chart generation

        Note:
            Classes with no assigned fees are grouped under 'Unknown'.
            Only classes with revenue > 0 are included in the chart.
        """
        try:
            # Get all unique classes and their revenues
            students_result = await db.execute(select(DBStudent))
            students = students_result.scalars().all()
            revenue_by_class = {}

            for student in students:
                if student.fees is not None:
                    class_name = student.class_ or 'Unknown'
                    if class_name not in revenue_by_class:
                        revenue_by_class[class_name] = 0
                    revenue_by_class[class_name] += student.fees

            # Sort by revenue
            sorted_classes = sorted(revenue_by_class.items(), key=lambda x: x[1], reverse=True)

            labels = [item[0] for item in sorted_classes]
            values = [item[1] for item in sorted_classes]
            colors = ['#667eea', '#764ba2', '#f093fb', '#f5576c', '#4facfe', '#00f2fe', '#43e97b', '#38f9d7']

            return {
                "labels": labels,
                "values": values,
                "colors": colors[:len(labels)],
                "type": "bar",
                "title": "Revenue by Class"
            }
        except Exception as e:
            raise HTTPException(status_code=500, detail=f"Error generating revenue by class chart: {str(e)}")